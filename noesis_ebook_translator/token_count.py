"""Token counting for the cost estimate: ``tiktoken`` with an offline fallback.

The wizard estimates how many tokens a book costs before translating it. The
honest counter is the model's own tokenizer, and for OpenAI models (and for the
gateways that serve them) that is ``tiktoken``. Two constraints shape this
module:

* **Offline.** ``tiktoken`` downloads its BPE file on first use into the system
  temp directory. A reboot can wipe it and an AppImage folder is read-only, so
  the two encodings ship inside the package (``data/tiktoken``) and
  ``TIKTOKEN_CACHE_DIR`` points there. If the files are missing anyway, the
  estimator must still work: it falls back to a script-aware heuristic instead
  of failing the wizard.
* **Non-OpenAI providers.** Claude/Gemini/Llama use different tokenizers;
  counting them with ``o200k_base`` is an approximation (usually within
  ±10–20%). The UI labels it as such. For OpenAI models the count is exact.

Nothing here performs network I/O at import time.
"""
from __future__ import annotations

import os
import threading
from pathlib import Path

__all__ = [
    "count", "count_many", "encoding_name_for", "backend", "configure_cache",
    "BUNDLE_DIR",
]

#: Bundled BPE files, named the way ``tiktoken`` names its cache entries
#: (SHA-1 of the download URL). Regenerated by ``tools/fetch_token_encodings.py``.
BUNDLE_DIR = Path(__file__).resolve().parent / "data" / "tiktoken"

#: Modern OpenAI tokenizer: GPT-4o, GPT-4.1, GPT-5.x, GPT-6.x, o1/o3/o4.
_O200K_PREFIXES = (
    "gpt-4o", "gpt-4.1", "gpt-4.5", "gpt-5", "gpt-6", "chatgpt-4o",
    "o1", "o3", "o4",
)
#: Older OpenAI tokenizers.
_CL100K_PREFIXES = (
    "gpt-4", "gpt-3.5", "gpt-35", "text-embedding-ada", "text-embedding-3",
)
_P50K_PREFIXES = (
    "code-davinci", "text-davinci-002", "text-davinci-003", "code-cushman",
)

#: Heuristic weights (characters per token) used only when tiktoken is unusable.
_WEIGHTS = {
    "latin": 3.9,
    "cyrillic": 2.4,
    "arabic": 2.5,
    "kana": 0.9,
    "cjk": 1.5,
    "hangul": 1.2,
    "other": 2.8,
}

_lock = threading.Lock()
_encoders: dict[str, object] = {}
#: Set once loading fails, so a missing bundle does not retry (and re-raise) for
#: every segment of a 20k-segment book.
_load_failed = False


def configure_cache() -> None:
    """Point ``tiktoken`` at the bundled encodings (respect an explicit override)."""
    os.environ.setdefault("TIKTOKEN_CACHE_DIR", str(BUNDLE_DIR))


def encoding_name_for(model: str | None) -> str:
    """The tiktoken encoding that best matches ``model``.

    Unknown (non-OpenAI) models map to ``o200k_base``: it is the closest modern
    BPE and, unlike ``cl100k_base``, handles the newer token distributions.
    """
    name = (model or "").strip().lower()
    # OpenRouter-style ids ("openai/gpt-4o-mini", "deepseek/deepseek-chat").
    name = name.rsplit("/", 1)[-1]
    if any(name.startswith(prefix) for prefix in _P50K_PREFIXES):
        return "p50k_base"
    # o200k before cl100k: "gpt-4o" and "gpt-4.1" also start with "gpt-4".
    if any(name.startswith(prefix) for prefix in _O200K_PREFIXES):
        return "o200k_base"
    if any(name.startswith(prefix) for prefix in _CL100K_PREFIXES):
        return "cl100k_base"
    return "o200k_base"


def _encoder(model: str | None):
    """Return a tiktoken encoder, or ``None`` when only the heuristic is usable."""
    global _load_failed
    encoding = encoding_name_for(model)
    with _lock:
        if encoding in _encoders:
            return _encoders[encoding]
        if _load_failed:
            return None
        try:
            configure_cache()
            import tiktoken  # lazy: the app must start even without the wheel

            encoder = tiktoken.get_encoding(encoding)
        except Exception:  # noqa: BLE001 - missing wheel/cache: use the fallback
            _load_failed = True
            return None
        _encoders[encoding] = encoder
        return encoder


def backend(model: str | None = None) -> str:
    """``"tiktoken"`` or ``"heuristic"`` (used by the estimate page)."""
    return "tiktoken" if _encoder(model) is not None else "heuristic"


def _heuristic_tokens(text: str) -> int:
    """Script-aware approximation (characters per token), used as a fallback."""
    if not text:
        return 0
    counts = dict.fromkeys(_WEIGHTS, 0)
    for char in text:
        code = ord(char)
        if code < 0x0250:                       # ASCII, Latin-1/Extended
            counts["latin"] += 1
        elif 0x0400 <= code < 0x0500:           # Cyrillic
            counts["cyrillic"] += 1
        elif 0x0600 <= code < 0x0700:           # Arabic
            counts["arabic"] += 1
        elif 0x3040 <= code < 0x30A0:           # Hiragana/Katakana
            counts["kana"] += 1
        elif (0x3400 <= code < 0x4DC0
              or 0x4E00 <= code < 0xA000):      # CJK ideographs
            counts["cjk"] += 1
        elif 0xAC00 <= code < 0xD7B0:           # Hangul
            counts["hangul"] += 1
        else:
            counts["other"] += 1
    tokens = sum(counts[key] / weight for key, weight in _WEIGHTS.items())
    return max(1, int(round(tokens)))


def count_many(texts, model: str | None = None) -> list[int]:
    """Token count of every string in ``texts`` (order preserved)."""
    items = ["" if text is None else str(text) for text in texts]
    encoder = _encoder(model)
    if encoder is not None:
        try:
            # ``encode_ordinary`` treats special-token lookalikes as plain text:
            # a book mentioning "<|endoftext|>" must not raise.
            return [len(tokens) for tokens in encoder.encode_ordinary_batch(items)]
        except Exception:  # noqa: BLE001 - never break the estimate
            pass
    return [_heuristic_tokens(item) for item in items]


def count(text: str, model: str | None = None) -> int:
    """Token count of one string (``0`` for empty text)."""
    if not text:
        return 0
    return count_many([text], model)[0]


def _reset_for_tests() -> None:
    """Drop loaded encoders (tests only)."""
    global _load_failed
    with _lock:
        _encoders.clear()
        _load_failed = False
